import { createHash } from 'crypto';
import { readFileSync } from 'fs';
import { join } from 'path';

const readProjectFile = (file: string) => readFileSync(join(__dirname, '..', file), 'utf8');

const cspHash = (source: string) => `'sha256-${createHash('sha256').update(source, 'utf8').digest('base64')}'`;

describe('Content Security Policy', () => {
  const scriptSrc = readProjectFile('nginx/additional-headers.yaml').match(/^\s*script-src[^;]*/m)?.[0];

  it('should define a script-src directive without unsafe-inline', () => {
    expect(scriptSrc).toBeTruthy();
    expect(scriptSrc).not.toContain(`'unsafe-inline'`);
  });

  it('should allow every inline script of index.html by its hash', () => {
    const inlineScripts = Array.from(readProjectFile('src/index.html').matchAll(/<script>([\s\S]*?)<\/script>/g)).map(
      match => match[1]
    );

    expect(inlineScripts).not.toBeEmpty();
    inlineScripts.forEach(script => expect(scriptSrc).toContain(cspHash(script)));
  });

  it('should allow the onload handler generated by the critical CSS inlining', () => {
    expect(scriptSrc).toContain(`'unsafe-hashes'`);
    expect(scriptSrc).toContain(cspHash(`this.media='all'`));
  });
});
