/**
 * Names of the tools the PWA handles; the chatflow can use further tools.
 */
export type CopilotEmbeddedToolName =
  | 'icmSearch'
  | 'PWA_ask_choice'
  | 'PWA_basket'
  | 'PWA_compare_products'
  | 'PWA_navigate_to_page'
  | 'PWA_order_template_actions';

/**
 * A tool call executed by the Flowise chatflow, e.g. an ICM product search.
 * Mirrors the structure the Copilot exposes via its embed.
 */
export interface CopilotEmbeddedToolCall {
  // `{} & string` keeps the editor suggestions for the known tools while other tool names stay valid
  tool: ({} & string) | CopilotEmbeddedToolName;
  /** Input of the tool, its shape depends on the tool, e.g. {@link CopilotEmbeddedBasketToolInput}. */
  toolInput: Record<string, unknown>;
  /** Result of the tool as returned to the language model, plain text or a JSON string; see e.g. `CopilotEmbeddedProductMapper` for the `icmSearch` output. */
  toolOutput?: string;
  /** Error thrown by the chatflow tool during execution, if any. */
  error?: string;
}

// The tool inputs are generated by the language model, so their shape is expected but not guaranteed.

/**
 * Input of the `PWA_basket` tool.
 */
export interface CopilotEmbeddedBasketToolInput {
  operation?: 'add' | 'clear' | 'remove' | 'update' | 'view';
  /** `sku:quantity` pairs separated by `;`, e.g. `123:2;456:1`; the quantity `all` removes the whole line item. */
  items?: string;
}

/**
 * Input of the `PWA_compare_products` tool.
 */
export interface CopilotEmbeddedCompareToolInput {
  /** SKUs separated by `;`, e.g. `123;456`. */
  SKUs?: string;
}

/**
 * Pages the `PWA_navigate_to_page` tool can navigate to.
 */
export type CopilotEmbeddedNavigationPage =
  | 'basket'
  | 'category'
  | 'contact'
  | 'home'
  | 'imprint'
  | 'login'
  | 'logout'
  | 'myAccount'
  | 'order'
  | 'orderHistory'
  | 'orderTemplate'
  | 'orderTemplates'
  | 'product';

/**
 * Input of the `PWA_navigate_to_page` tool; the ID belonging to the page is required, e.g. `sku` for `product`.
 */
export interface CopilotEmbeddedNavigateToolInput {
  page?: CopilotEmbeddedNavigationPage;
  sku?: string;
  categoryId?: string;
  orderId?: string;
  orderTemplateId?: string;
}

/**
 * Input of the `PWA_order_template_actions` tool.
 */
export interface CopilotEmbeddedOrderTemplateToolInput {
  operation?: 'add' | 'create' | 'delete' | 'remove';
  /** Title of the order template to create. */
  title?: string;
  orderTemplateId?: string;
  sku?: string;
  /** Quantity of the product to add, defaults to 1. */
  quantity?: number | string;
}
